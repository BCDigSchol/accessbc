#!/usr/bin/env bash
# Rebuilds the self-hosted basemap in src/basemap/. Only needed to refresh OpenStreetMap
# data or change the basemap style; the site itself never runs this.
#
# Requires: node/npm, python3, and the pmtiles CLI (https://github.com/protomaps/go-pmtiles/releases)
# Usage: scripts/build-basemap.sh [flavor]   (flavor: light, grayscale, white, dark, black)
set -euo pipefail

FLAVOR="${1:-white}"
REPO="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$REPO/src/basemap"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# Area covering all four campuses. The map's maxBounds in src/js/map.js matches BASEMAP_BBOX.
BASEMAP_BBOX="-71.215,42.305,-71.135,42.360"
TERRAIN_BBOX="-71.200,42.314,-71.150,42.351"

# 1. Basemap vector tiles: cut the campus area out of the latest Protomaps planet build.
BUILD="$(curl -s https://build-metadata.protomaps.dev/builds.json | python3 -c 'import json,sys; print(json.load(sys.stdin)[-1]["key"])')"
pmtiles extract "https://build.protomaps.com/$BUILD" "$OUT/basemap.pmtiles" --bbox="$BASEMAP_BBOX" --maxzoom=15

# 2. Terrain: Terrarium-encoded elevation tiles (AWS Open Data Terrain Tiles), zooms 11-15.
python3 - "$TERRAIN_BBOX" "$WORK/terrain.mbtiles" <<'EOF'
import math, sqlite3, sys, urllib.request
W, S, E, N = map(float, sys.argv[1].split(','))
tx = lambda lon, z: int((lon + 180) / 360 * 2**z)
def ty(lat, z):
    r = math.radians(lat)
    return int((1 - math.log(math.tan(r) + 1 / math.cos(r)) / math.pi) / 2 * 2**z)
db = sqlite3.connect(sys.argv[2])
db.execute('create table metadata(name text, value text)')
db.execute('create table tiles(zoom_level int, tile_column int, tile_row int, tile_data blob)')
meta = {'name': 'terrain', 'format': 'png', 'minzoom': '11', 'maxzoom': '15', 'type': 'baselayer',
        'bounds': sys.argv[1], 'attribution': 'Terrain Tiles (AWS Open Data): USGS 3DEP and others'}
db.executemany('insert into metadata values(?, ?)', meta.items())
for z in range(11, 16):
    for x in range(tx(W, z), tx(E, z) + 1):
        for y in range(ty(N, z), ty(S, z) + 1):
            png = urllib.request.urlopen(f'https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{z}/{x}/{y}.png').read()
            db.execute('insert into tiles values(?, ?, ?, ?)', (z, x, 2**z - 1 - y, png))
db.commit()
EOF
pmtiles convert "$WORK/terrain.mbtiles" "$OUT/terrain.pmtiles"

# 3. Style layers, generated from @protomaps/basemaps. Labels above zoom 12 only need these glyph ranges.
(cd "$WORK" && npm init -y >/dev/null && npm i --silent @protomaps/basemaps@5.7.2)
# Layer ids get a basemap- prefix so they can't collide with the app's own layers (e.g. buildings).
NODE_PATH="$WORK/node_modules" node -e "
const { layers, namedFlavor } = require('@protomaps/basemaps');
const basemap = layers('protomaps', namedFlavor('$FLAVOR'), { lang: 'en' }).map(l => ({ ...l, id: 'basemap-' + l.id }));
const out = '// Generated by scripts/build-basemap.sh (@protomaps/basemaps 5.7.2, flavor: $FLAVOR). Do not edit by hand.\n'
  + 'const BASEMAP_FLAVOR = ' + JSON.stringify('$FLAVOR') + ';\n'
  + 'const BASEMAP_LAYERS = ' + JSON.stringify(basemap, null, 1) + ';\n';
require('fs').writeFileSync('$OUT/style.js', out);
"

ASSETS="https://protomaps.github.io/basemaps-assets"
for font in "Noto Sans Regular" "Noto Sans Medium" "Noto Sans Italic"; do
  mkdir -p "$OUT/fonts/$font"
  for range in 0-255 256-511 8192-8447; do
    curl -sf -o "$OUT/fonts/$font/$range.pbf" "$ASSETS/fonts/${font// /%20}/$range.pbf"
  done
done
mkdir -p "$OUT/sprites"
for suffix in "" "@2x"; do
  for ext in json png; do
    curl -sf -o "$OUT/sprites/$FLAVOR$suffix.$ext" "$ASSETS/sprites/v4/$FLAVOR$suffix.$ext"
  done
done

echo "Basemap rebuilt from $BUILD ($FLAVOR)."
