// Writes docs/usability-testing/instruction-samples.md: the step-by-step instructions Access BC gives for a set of
// real routes, plus the other things it says while guiding, for an orientation and mobility (O&M) instructor
// or a blind student to review. Uses the same graph and instruction code as the site.
//
// Usage: node scripts/routing/sample-instructions.mjs
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, load, buildGraph, routeBetweenBuildings } from './lib.mjs';
import { buildSteps } from '../../src/js/routing/guidance.mjs';

// Routes chosen to cover short and long walks, indoor stretches, and busy parts of Middle Campus.
// Pairs that can't be routed (no accessible entrance on the network) are skipped and listed.
const PAIRS = [
  ['Gasson Hall', 'McElroy Commons'],
  ["O'Neill Library", 'Gasson Hall'],
  ['Fulton Hall', 'Carney Hall'],
  ['Devlin Hall', 'Higgins Hall'],
  ["O'Neill Library", 'Merkert Chemistry Center'],
  ['McElroy Commons', 'Campion Hall'],
  ['Stokes Hall', 'Fulton Hall'],
  ['Lyons Hall', 'Cushing Hall'],
];

const data = { paths: load('accessiblepaths.geojson'), entrances: load('entrances.geojson'), buildings: load('buildings.geojson'), elevators: load('elevators.geojson') };
const graph = buildGraph(data);
const feet = (m) => `${Math.round(m * 3.28084).toLocaleString()} ft`;

const sections = [], skipped = [];
for (const [from, to] of PAIRS) {
  const route = routeBetweenBuildings(graph, from, to);
  if (!route) { skipped.push(`${from} to ${to}`); continue; }
  const steps = buildSteps(graph, route, { from, to });
  sections.push(`### ${from} to ${to} (${feet(route.length)}, ${steps.length} steps)\n\n${steps.map((s, i) => `${i + 1}. ${s.text}`).join('\n')}\n`);
}

const out = `# Sample directions for review

Generated by \`scripts/routing/sample-instructions.mjs\` from the live routing data. Regenerate it after changing
how instructions are worded (\`src/js/routing/guidance.mjs\`, \`src/js/orientation.js\`, \`src/js/guidance.js\`).

These are the instructions Access BC shows and reads aloud in step-by-step directions. Please read them as if
you were walking the route without sight, and note anything that's unclear, unhelpful, missing, or unsafe.
[review-guide.md](review-guide.md) has questions to guide the review.

## Routes

${sections.join('\n')}${skipped.length ? `\nNot routable with the current data: ${skipped.join('; ')}.\n` : ''}
## Other things Access BC says while guiding

Examples; distances, directions, and names change with the route.

| When | What it says |
|---|---|
| Setting off, after a stop, leaving a building (with the phone's compass) | “The way to go is at your 2 o’clock.” |
| Without a compass | Directions use compass points: “head south”, “to the northeast”. |
| About 20 m before the next step (following location) | “Soon: Turn left and continue for 120 feet, with Fulton Hall on your right.” |
| A curb ramp on the step | “Curb ramp about 55 ft ahead, often where a street or driveway is crossed.” |
| Stairs branching off the route | “Stairs branch off on your left about 20 ft ahead. Stay on the level path.” |
| Seating on a long stretch | “Outdoor seating on your right about 80 ft ahead.” |
| Slope of a step | “Gentle: up to 3.2% uphill.” / “Steep: up to 9.1% downhill, steeper than 1:12.” |
| Off the route | “You seem to be off the route. It’s about 110 ft away, at your 9 o’clock.” |
| Indoors, while following | “Location is less reliable indoors. Use Next when you reach the end of this step.” |
| Face the right way | “Turn right: the way to go is at your 3 o’clock.” … “Facing the right way.” |
| Where am I? | “You’re about 40 ft from Gasson Hall, at your 10 o’clock. You’re on your route. In about 35 ft: Turn left…” |
| What’s around (Where am I?) | “Accessible entrance of Devlin Hall: about 80 ft, at your 4 o’clock.” |
| Arrival | “Arrive at the accessible entrance of McElroy Commons. It’s on your right.” |

Sounds and vibration: one tone for a new step (from the side of a turn, with headphones); two quick high tones
for a turn coming up; two falling tones for leaving the route; three rising tones on arrival. On Android, two
pulses for a left turn, three for a right, long-short-long at a stop or the destination.
`;
const file = path.join(ROOT, 'docs/usability-testing/instruction-samples.md');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, out);
console.log(`Wrote ${path.relative(ROOT, file)}: ${sections.length} routes${skipped.length ? `, skipped ${skipped.length}` : ''}.`);
